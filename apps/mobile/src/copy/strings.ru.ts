function pluralRu(n: number, one: string, few: string, many: string): string {
  const abs = Math.abs(n), m10 = abs % 10, m100 = abs % 100;
  return `${n} ${m10 === 1 && m100 !== 11 ? one : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? few : many}`;
}

