// Romanian adds "de" after whole numbers ≥ 20 whose last two digits are 00 or 20–99.
function withDe(n: number): boolean {
  const r = n % 100;
  return Number.isInteger(n) && n >= 20 && (r === 0 || r >= 20);
}

export function plural(n: number, one: string, many: string): string {
  if (n === 1) return `1 ${one}`;
  return `${n} ${withDe(n) ? 'de ' : ''}${many}`;
}

