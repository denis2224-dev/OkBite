import { lstat, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, extname, join, posix } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = join(root, 'packages/shared/src');
const output = join(root, 'supabase/functions/_shared');
const header = '// GENERATED by pnpm sync-shared — do not edit\n';
const testDirectories = new Set(['test', 'tests', '__tests__', '__mocks__']);

async function collect(directory, prefix = '') {
  const files = new Map();
  const entries = await readdir(directory, { withFileTypes: true });
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const path = join(directory, entry.name);
    const name = `${prefix}${entry.name}`;
    if (entry.isDirectory() && !testDirectories.has(entry.name)) {
      for (const [nested, content] of await collect(path, `${name}/`)) files.set(nested, content);
    } else if (entry.isFile() && entry.name.endsWith('.ts') && !/(?:^|\.)(test|spec)\.ts$/.test(entry.name)) {
      files.set(name, await readFile(path, 'utf8'));
    }
  }
  return files;
}

function moduleName(name, filename, files) {
  if (name === 'zod') return 'npm:zod@3.23.8';
  if (!name.startsWith('./') && !name.startsWith('../')) return name;
  const extension = extname(name);
  const explicit = extension === '.js' || extension === '.ts';
  const base = explicit ? name.slice(0, -extension.length) : name.replace(/\/$/, '');
  const candidates = explicit ? [`${base}.ts`] : [`${base}.ts`, `${base}/index.ts`];
  const match = candidates.find((candidate) => files.has(posix.join(posix.dirname(filename), candidate)));
  if (!match && extension && !explicit) return name;
  if (!match) throw new Error(`Cannot resolve shared module ${name} from ${filename}`);
  return match;
}

function transform(filename, content, files) {
  const parsed = ts.createSourceFile(filename, content, ts.ScriptTarget.Latest, true);
  const edits = [];
  function visit(node) {
    let reference;
    if (ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) reference = node.moduleSpecifier;
    else if (ts.isCallExpression(node) && node.expression.kind === ts.SyntaxKind.ImportKeyword) {
      reference = node.arguments[0];
    } else if (ts.isImportTypeNode(node) && ts.isLiteralTypeNode(node.argument)) {
      reference = node.argument.literal;
    }
    if (reference && (ts.isStringLiteral(reference) || ts.isNoSubstitutionTemplateLiteral(reference))) {
      const replacement = moduleName(reference.text, filename, files);
      if (replacement !== reference.text) {
        edits.push({ start: reference.getStart(parsed) + 1, end: reference.getEnd() - 1, replacement });
      }
    }
    ts.forEachChild(node, visit);
  }
  visit(parsed);
  for (const { start, end, replacement } of edits.sort((a, b) => b.start - a.start)) {
    content = content.slice(0, start) + replacement + content.slice(end);
  }
  return header + content;
}

// Resolve every module before clearing the generated directory, so invalid inputs
// leave the previous output intact. Cleanup is confined to this generated tree.
const files = await collect(source);
const generated = new Map([...files].map(([name, content]) => [name, transform(name, content, files)]));
for (const path of [join(root, 'supabase'), join(root, 'supabase/functions'), output]) {
  const info = await lstat(path).catch((error) => {
    if (error.code !== 'ENOENT') throw error;
  });
  if (info?.isSymbolicLink()) throw new Error(`Refusing symbolic link in generated output path: ${path}`);
}
await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });
for (const [name, content] of generated) {
  const target = join(output, name);
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, content);
}
