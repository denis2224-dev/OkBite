import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { cp, mkdir, mkdtemp, readFile, readdir, rm, symlink, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';

const directoryLink = process.platform === 'win32' ? 'junction' : 'dir';
const repo = fileURLToPath(new URL('../', import.meta.url));
const header = '// GENERATED by pnpm sync-shared — do not edit\n';

async function put(root, path, content) {
  const target = join(root, path);
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, content);
}

async function fixture(t, files) {
  const root = await mkdtemp(join(tmpdir(), 'okbite-sync-shared-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  await mkdir(join(root, 'scripts'));
  await cp(join(repo, 'scripts/sync-shared.mjs'), join(root, 'scripts/sync-shared.mjs'));
  await symlink(join(repo, 'node_modules'), join(root, 'node_modules'), directoryLink);
  for (const [path, content] of Object.entries(files)) {
    await put(root, `packages/shared/src/${path}`, content);
  }
  const output = join(root, 'supabase/functions/_shared');
  const run = () => spawnSync(process.execPath, [join(root, 'scripts/sync-shared.mjs')], {
    cwd: tmpdir(), encoding: 'utf8',
  });
  return { root, output, run };
}

function succeeds(run) {
  const result = run();
  assert.equal(result.status, 0, result.stderr);
}

async function snapshot(directory, prefix = '') {
  const files = {};
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    const name = `${prefix}${entry.name}`;
    if (entry.isDirectory()) Object.assign(files, await snapshot(path, `${name}/`));
    else files[name] = await readFile(path, 'utf8');
  }
  return files;
}

test('copies nested TypeScript with headers, excluding tests and other assets', async (t) => {
  const { output, run } = await fixture(t, {
    'index.ts': "export * from './nested/value';\n",
    'nested/value.ts': 'export const value = 1;\n',
    'nested/value.test.ts': 'test code',
    'nested/value.spec.ts': 'spec code',
    '__tests__/helper.ts': 'test helper',
    '__mocks__/helper.ts': 'test mock',
    'tests/fixture.ts': 'test fixture',
    'test/fixture.ts': 'test fixture',
    'test.ts': 'test entry',
    'notes.md': 'not TypeScript',
  });
  succeeds(run);
  assert.deepEqual(await snapshot(output), {
    'index.ts': header + "export * from './nested/value.ts';\n",
    'nested/value.ts': header + 'export const value = 1;\n',
  });
});

test('rewrites static, dynamic, type and barrel module references for Deno', async (t) => {
  const source = [
    "import { z } from 'zod';",
    'import type { ZodType } from "zod";',
    "export { z } from 'zod';",
    "import './value';",
    'export * from "./nested";',
    "export type { Value } from './value';",
    "import type { Value } from './value.ts';",
    "const lazy = import('./value');",
    'const template = import(`./value`);',
    "type ValueType = import('./value').Value;",
    "const schema = import('zod');",
    "export * from './value.js';",
    "export * from './score.rules';",
    "import 'other-package';",
    "import 'https://example.com/module.ts';",
    '',
  ].join('\n');
  const expected = source
    .replaceAll("'zod'", "'npm:zod@3.23.8'")
    .replaceAll('"zod"', '"npm:zod@3.23.8"')
    .replaceAll("'./value'", "'./value.ts'")
    .replaceAll('`./value`', '`./value.ts`')
    .replaceAll('"./nested"', '"./nested/index.ts"')
    .replaceAll("'./value.js'", "'./value.ts'")
    .replaceAll("'./score.rules'", "'./score.rules.ts'");
  const { output, run } = await fixture(t, {
    'index.ts': source,
    'value.ts': 'export type Value = number;\n',
    'score.rules.ts': 'export const rule = true;\n',
    'nested/index.ts': "export * from '../value';\n",
  });
  succeeds(run);
  assert.equal(await readFile(join(output, 'index.ts'), 'utf8'), header + expected);
  assert.equal(await readFile(join(output, 'nested/index.ts'), 'utf8'),
    header + "export * from '../value.ts';\n");
});

test('preserves comments, strings and import attributes verbatim', async (t) => {
  const source = [
    "// import { z } from 'zod';",
    '/* export * from "./value"; */',
    'const text = "import(\'./value\')";',
    "const name = 'zod';",
    "import data from './data.json' with { type: 'json' };",
    '',
  ].join('\n');
  const { output, run } = await fixture(t, { 'index.ts': source });
  succeeds(run);
  assert.equal(await readFile(join(output, 'index.ts'), 'utf8'), header + source);
});

test('is repeatable and removes stale files without touching sibling helpers or sources', async (t) => {
  const { root, output, run } = await fixture(t, {
    'index.ts': 'export const current = true;\n',
    'obsolete/nested.ts': 'export const old = true;\n',
  });
  await put(root, 'supabase/functions/_lib/keep.ts', 'keep helper');
  succeeds(run);
  const first = await snapshot(output);
  succeeds(run);
  assert.deepEqual(await snapshot(output), first);
  await rm(join(root, 'packages/shared/src/obsolete'), { recursive: true });
  await put(root, 'supabase/functions/_shared/stale.txt', 'stale artifact');
  await symlink(join(root, 'supabase/functions/_lib'), join(output, 'stale-link'), directoryLink);
  succeeds(run);
  assert.deepEqual(await snapshot(output), { 'index.ts': first['index.ts'] });
  assert.equal(await readFile(join(root, 'supabase/functions/_lib/keep.ts'), 'utf8'), 'keep helper');
  assert.equal(await readFile(join(root, 'packages/shared/src/index.ts'), 'utf8'),
    'export const current = true;\n');
});

test('fails before clearing existing output when a relative module is missing', async (t) => {
  const { root, output, run } = await fixture(t, {
    'index.ts': "export * from './missing';\n",
  });
  await put(root, 'supabase/functions/_shared/keep.ts', 'previous output');
  const result = run();
  assert.notEqual(result.status, 0);
  assert.match(result.stderr, /missing/);
  assert.equal(await readFile(join(output, 'keep.ts'), 'utf8'), 'previous output');
});

test('refuses a symlinked output directory without touching its target', async (t) => {
  const { root, output, run } = await fixture(t, { 'index.ts': 'export {};\n' });
  await put(root, 'supabase/functions/_lib/keep.ts', 'keep helper');
  await symlink(join(root, 'supabase/functions/_lib'), output, directoryLink);
  const result = run();
  assert.notEqual(result.status, 0);
  assert.match(result.stderr, /symbolic link/i);
  assert.equal(await readFile(join(output, 'keep.ts'), 'utf8'), 'keep helper');
});
